import { readFile, writeFile, mkdir, mkdtemp, rm } from "node:fs/promises";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

// Pin and verify an official Safari release. Updating is an explicit developer
// operation; the installed extension never downloads or evaluates remote code.
const release = "2026.1021.1354";
const digest = "6c80d19c128cd3f6b5d1ff2ef151fa0ff31565da3c5ef6841443381702b92838";
const url = `https://github.com/uBlockOrigin/uBOL-home/releases/download/${release}/uBOLite_${release}.safari.zip`;
const root = fileURLToPath(new URL("../", import.meta.url));
const vendor = join(root, "extension/vendor/youtube");
const hosts = ["youtube.com", "www.youtube.com", "m.youtube.com", "music.youtube.com", "tv.youtube.com", "youtube-nocookie.com", "www.youtube-nocookie.com"];
const tempRoot = join(tmpdir(), "opencode");
await mkdir(tempRoot, { recursive: true });
const temporary = await mkdtemp(join(tempRoot, "stil-youtube-"));

try {
  let archive;
  if (process.argv[2]) archive = await readFile(process.argv[2]);
  else {
    const response = await fetch(url);
    if (!response.ok) throw new Error(`Download failed: ${response.status}`);
    archive = Buffer.from(await response.arrayBuffer());
  }
  if (createHash("sha256").update(archive).digest("hex") !== digest) throw new Error("Upstream archive checksum mismatch.");
  const archivePath = join(temporary, "upstream.zip");
  await writeFile(archivePath, archive);
  const extract = name => execFileSync("unzip", ["-p", archivePath, name], { maxBuffer: 20 * 1024 * 1024 }).toString("utf8");
  await mkdir(join(vendor, "upstream/main"), { recursive: true });
  await mkdir(join(vendor, "upstream/isolated"), { recursive: true });
  const license = extract("LICENSE.txt");
  await writeFile(join(vendor, "LICENSE.txt"), license);
  await writeFile(join(root, "LICENSE"), license);
  const provenance = { release, url, sha256: digest, license: "GPL-3.0-or-later", hosts, worlds: {} };

  for (const world of ["main", "isolated"]) {
    const prefix = `rulesets/scripting/scriptlet/${world}/`;
    const begin = extract(prefix + "scriptlet-begin.js");
    const rules = extract(prefix + "ublock-filters.js");
    const end = extract(prefix + "scriptlet-end.js");
    // Retain complete, unmodified corresponding sources as well as the derived
    // YouTube-only bundles. The original license/copyright notices are kept.
    for (const [name, source] of Object.entries({ "scriptlet-begin.js": begin, "ublock-filters.js": rules, "scriptlet-end.js": end })) {
      await writeFile(join(vendor, "upstream", world, name), source);
    }
    function array(name) {
      const match = rules.match(new RegExp(`const ${name} = (?:/\\*.*?\\*/ )?(\\[.*\\]);`));
      if (!match) throw new Error(`Unrecognized upstream format: ${world}/${name}`);
      return JSON.parse(match[1]);
    }
    const upstreamHosts = array("scriptletHostnames");
    const refs = array("arglistRefs");
    const arglists = array("arglists");
    const args = array("args");
    const secret = /\}\)\("([a-f0-9-]+)"\);/.exec(end)?.[1];
    if (!secret || !begin.includes(secret) || !rules.includes(secret)) throw new Error("Mismatched scriptlet framework.");
    const selected = {};
    for (const host of hosts) {
      const todo = new Set();
      for (let suffix = host; suffix.includes("."); suffix = suffix.slice(suffix.indexOf(".") + 1)) {
        const index = upstreamHosts.indexOf(suffix);
        if (index !== -1) for (const ref of JSON.parse(`[${refs[index]}]`)) todo.add(ref);
      }
      selected[host] = [...todo].filter(ref => ref > 0 && !todo.has(~ref)).map(ref => {
        const [fn, ...indices] = JSON.parse(`[${arglists[ref]}]`);
        return [fn, ...indices.map(index => args[index])];
      });
    }
    provenance.worlds[world] = Object.fromEntries(Object.entries(selected).map(([host, calls]) => [host, calls.length]));
    const marker = world === "main" ? "__stilYoutubeMain" : "__stilYoutubeIsolated";
    const header = `/* Generated by scripts/update-youtube.mjs from the pinned upstream release ${release}.
 * GPL-3.0-or-later. Copyright Raymond Hill and contributors.
 * Modification: restrict invocation data to YouTube; add Stil injection status.
 * Corresponding sources: vendor/youtube/upstream/. */\n`;
    const runner = `
const callsByHost = ${JSON.stringify(selected, null, 2)};
const framework = globalThis[${JSON.stringify(secret)}];
for (const [index, ...args] of callsByHost[host]) {
  state.attempted++;
  try { framework.functionRefs[index](...args); }
  catch { state.failed++; }
}
state.ready = state.failed === 0;
`;
    const announcement = world === "main" ? `
const announce = () => document.dispatchEvent(new CustomEvent("stil-youtube-status", { detail: JSON.stringify(state) }));
document.addEventListener("stil-youtube-status-request", announce);
announce();
` : "";
    const bundle = `${header}(() => {
const host = location.hostname.toLowerCase().replace(/\\.$/, "");
if (!${JSON.stringify(hosts)}.includes(host) || globalThis.${marker}) return;
const state = globalThis.${marker} = { release: ${JSON.stringify(release)}, version: "0.3.0", ready: false, attempted: 0, failed: 0, phase: document.readyState };
${begin}
${runner}
${end}
${announcement}
})();\n`;
    await writeFile(join(vendor, `youtube-${world}.js`), bundle);
  }

  // Preserve only network rules explicitly originating on YouTube, with no
  // redirects or external resource dependencies. Existing site allows outrank
  // these rules. 'domains' is the Safari-compatible initiator-domain alias.
  const upstreamNetwork = extract("rulesets/main/ublock-filters.json");
  await writeFile(join(vendor, "upstream/network.json"), upstreamNetwork);
  const network = JSON.parse(upstreamNetwork).filter(rule =>
    rule.action.type === "block" && rule.condition.initiatorDomains?.includes("youtube.com")
  ).map((rule, index) => {
    const condition = { ...rule.condition, domains: ["youtube.com"] };
    delete condition.initiatorDomains;
    return { ...rule, id: index + 1, condition };
  });
  if (!network.length) throw new Error("No YouTube network rules found; review upstream changes.");
  await writeFile(join(vendor, "youtube-network.json"), JSON.stringify(network, null, 2) + "\n");
  provenance.networkRules = network.length;
  await writeFile(join(vendor, "provenance.json"), JSON.stringify(provenance, null, 2) + "\n");
  console.log(`Bundled upstream YouTube filters ${release}: both execution worlds and ${network.length} network rules.`);
} finally {
  await rm(temporary, { recursive: true, force: true });
}
